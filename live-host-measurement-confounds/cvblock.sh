#!/bin/sh
# cvblock.sh - one fresh cv daemon block (K2/K3), meant to run inside the lhmc-bench container.
# usage: cvblock.sh <A|B>
# One invocation = one fresh daemon on the scratch vault; requests inside it are within-invocation repetitions.
# Prints "MEASURE <metric> <value> [unit]" lines (details to stderr).
#   A (K3): PASSES view passes (+5 searches each), then AIDLE s idle. Metrics: anon_settled_mib (mean of the last 10 s),
#           anon_peak_mib, bad_mode (1 if settled > 75 MiB), view_p95_ms, daemon_cpu_s, cpuset_n, daemon_errors.
#   B (K2): BLOAD s job replay loop + a pipelined view pass every BPASS s, then AIDLE s idle. Metrics: view_p95_ms,
#           dupes_scan_p95_ms, link_scan_all_p95_ms, daemon_cpu_s, anon_settled_mib, cpuset_n, daemon_errors.
# Env: PASSES (3), AIDLE (30), BLOAD (60), BPASS (15), LHMC_SCRATCH (/scratch: pristine/, ro/search.db, notes.txt),
#      LHMC_CV (/cvbin/cv), LHMC_BLK (/blk, writable mount; the block works in <LHMC_BLK>/work), LHMC_HERE (/lhmc).
# >>> shguard modes=exec (generated by shell-disposition-gate --guard; do not edit)
case $(realpath -- "$0" 2>/dev/null) in */'cvblock.sh') _shguard_m='exec' ;; *) if [ "${SHGUARD_MODE-}" = 'pipe' ]; then _shguard_m='pipe'; else _shguard_m='source'; fi ;; esac
# shellcheck disable=SC2317
case $_shguard_m in
  exec) unset _shguard_m ;;
  *) printf '%s: refusing %s invocation (supports: exec; pipe callers set SHGUARD_MODE=pipe)\n' 'cvblock.sh' "$_shguard_m" >&2; unset _shguard_m; return 1 2>/dev/null || exit 1 ;;
esac
# <<< shguard
if [ "${1:-}" = "--help" ] || [ "${1:-}" = "-h" ]; then
  echo "usage: cvblock.sh <A|B>"
  echo "       cvblock.sh --help | --build | --version"
  echo "One fresh cv daemon block on the scratch vault; prints MEASURE lines (see the header comment for metrics and env)."
  exit 0
fi
set -eu


case ${1:-} in
  --build|--version) exec "$(dirname "$0")/ctl" --build ;;
esac
scen=${1:?scenario A or B}
case $scen in A|B) ;; *) echo "cvblock.sh: scenario must be A or B" >&2; exit 2 ;; esac
S=${LHMC_SCRATCH:-/scratch}; BIN=${LHMC_CV:-/cvbin/cv}; R=${LHMC_BLK:-/blk}/work; D=${LHMC_HERE:-/lhmc}
PASSES=${PASSES:-3}; AIDLE=${AIDLE:-30}; BLOAD=${BLOAD:-60}; BPASS=${BPASS:-15}
[ "$AIDLE" -ge 10 ] || { echo "cvblock.sh: AIDLE must be >= 10 (settled = last 10 s)" >&2; exit 2; }

rm -rf "$R"; mkdir -p "$R/state" "$R/cache" "$R/run" "$R/data" "$R/hm"
cp "$S/ro/search.db" "$R/state/search.db"
export CV_VAULT=$S/pristine CV_CONFIG_DIR=$S/pristine/_custom/crucible-vault CV_STATE_DB=$R/state/state.db \
  CV_SEARCH_DB=$R/state/search.db CV_INDEX_DB=$R/cache/index.db CV_SOCKET=$R/run/cv.sock \
  XDG_DATA_HOME=$R/data XDG_RUNTIME_DIR=$R/run XDG_STATE_HOME=$R/state XDG_CACHE_HOME=$R/cache \
  XDG_CONFIG_HOME=$R/hm/.config HOME=$R/hm CV_LINK_WRITE_ROOTS=
unset CV_ROUTER_GATEWAY_KEY NOTIFY_SOCKET || true
"$BIN" daemon >"$R/daemon.log" 2>&1 &
pid=$!
samp=
cleanup() { [ -z "$samp" ] || kill "$samp" 2>/dev/null || true; kill "$pid" 2>/dev/null || true; rm -rf "$R"; }
trap cleanup EXIT INT TERM
i=0
while [ $i -lt 300 ]; do [ -S "$CV_SOCKET" ] && "$BIN" status >/dev/null 2>&1 && break; i=$((i + 1)); sleep 1; done
[ $i -lt 300 ] || { echo "cvblock.sh: daemon did not come up" >&2; exit 1; }
drain() {
  n=0
  while [ $n -lt 900 ]; do
    q=$("$BIN" status 2>/dev/null | grep -Eo '(queued|running)=[0-9]+' | grep -Eo '[0-9]+' | awk '{s+=$1} END{print s+0}') || q=0
    [ "${q:-0}" = 0 ] && break
    n=$((n + 1)); sleep 1
  done
}
drain; sleep 5
now_ms() { date +%s%3N; }
t0=$(now_ms)
ticks() { awk '{print $14+$15}' "/proc/$pid/stat"; }
c0=$(ticks)
( while kill -0 "$pid" 2>/dev/null; do
    printf '%s %s\n' "$(( $(now_ms) - t0 ))" "$(awk '/^RssAnon/{print $2}' "/proc/$pid/status")"
    sleep 0.5
  done >"$R/samples.txt" ) &
samp=$!
: >"$R/requests.txt"
pass() { perl "$D/client.pl" "$CV_SOCKET" "${PASSMODE:-views}" "${1:-5}" >>"$R/requests.txt"; }
case $scen in
  A)
    p=0; while [ $p -lt "$PASSES" ]; do pass 5; p=$((p + 1)); done
    sleep "$AIDLE" ;;
  B)
    ( end=$(( $(date +%s) + BLOAD ))
      while [ "$(date +%s)" -lt "$end" ]; do
        "$BIN" run link-scan-all >/dev/null 2>&1 || true
        "$BIN" run dupes-scan >/dev/null 2>&1 || true
        while IFS= read -r n; do "$BIN" run link-scan --note "$n" >/dev/null 2>&1 || true; done <"$S/notes.txt"
        drain
      done ) &
    jl=$!
    end=$(( $(date +%s) + BLOAD ))
    while [ "$(date +%s)" -lt "$end" ]; do PASSMODE=pipe pass 2; sleep "$BPASS"; done
    wait "$jl"; drain
    sleep "$AIDLE" ;;
esac
end=$(( $(now_ms) - t0 )); c1=$(ticks)
"$BIN" jobs stats >"$R/stats.txt" 2>&1 || true
errs=$(grep -cE 'ERROR|panicked' "$R/daemon.log" || true)
nthr=$(awk '/^Cpus_allowed_list/{n=split($2, p, ","); c=0; for (i = 1; i <= n; i++) { m = split(p[i], r, "-"); c += (m > 1) ? r[2] - r[1] + 1 : 1 } print c}' "/proc/$pid/status")
ok=$(grep -c ' ok$' "$R/requests.txt" || true); bad=$(grep -c ' err$' "$R/requests.txt" || true)
echo "cvblock $scen: requests ok=$ok err=$bad daemon_errors=$errs" >&2
pct() { sort -n | awk -v p="$1" '{a[NR]=$1} END{if(NR==0){print "NaN";exit} i=int(p*NR+0.999); if(i<1)i=1; printf "%.1f", a[i]}'; }
p95job() { awk -v a="action:$1" '$1==a{f=1;next} f&&$1=="run"{print $5; exit}' "$R/stats.txt" | awk '{v=$1; if (v ~ /ms$/) m=1; else if (v ~ /[0-9.]s$/) m=1000; else if (v ~ /s$/) m=0.001; else m=1; gsub(/[^0-9.]/, "", v); printf "%.1f", v * m}'; }
settled=$(awk -v e="$end" '$1>=e-10000&&$1<=e{s+=$2;n++} END{printf "%.2f", (n?s/n:0)/1024}' "$R/samples.txt")
peak=$(awk '{if($2>p)p=$2} END{printf "%.2f", p/1024}' "$R/samples.txt")
vp95=$(awk '$1=="view"{print $3}' "$R/requests.txt" | pct 0.95)
cpu=$(awk -v a="$c0" -v b="$c1" 'BEGIN{printf "%.2f", (b-a)/100}')
echo "MEASURE view_p95_ms $vp95 ms"
echo "MEASURE daemon_cpu_s $cpu s"
echo "MEASURE anon_settled_mib $settled MiB"
echo "MEASURE cpuset_n $nthr"
echo "MEASURE daemon_errors $errs"
if [ "$scen" = A ]; then
  echo "MEASURE anon_peak_mib $peak MiB"
  echo "MEASURE bad_mode $(awk -v s="$settled" 'BEGIN{print (s > 75) ? 1 : 0}')"
else
  d=$(p95job dupes-scan); l=$(p95job link-scan-all)
  echo "MEASURE dupes_scan_p95_ms ${d:-NaN} ms"
  echo "MEASURE link_scan_all_p95_ms ${l:-NaN} ms"
fi
